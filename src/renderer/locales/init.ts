/** Renderer-only language; never writes an omp setting. */
export async function initI18n(language = 'en'): Promise<void> {
  const lng = resolveLocale(language);
  if (i18next.isInitialized) {
    await i18next.changeLanguage(lng);
  } else {
    await i18next.use(initReactI18next).init({
      resources: Object.fromEntries(Object.entries(catalogs).map(([locale, catalog]) => {
        const redesign = [errorsMessages, toolsMessages, timelineMessages, subagentsMessages, shellMessages, composerMessages, reviewMessages, todoMessages, sidebarMessages, paletteMessages, historyMessages, objectsMessages, settingsMessages, homeMessages, inspectorMessages, compactionMessages, pagingMessages, motionMessages, meterMessages, turnMessages, observeMessages].map(messages => messages[locale as 'en' | 'zh-CN'] ?? {});
        return [locale, { translation: Object.assign({ ...flattenCatalog(catalog), ...desktopMessages[locale] }, ...redesign) }];
      })),
      lng,
      fallbackLng: 'en',
      interpolation: { escapeValue: false },
      returnNull: false,
    });
  }
  document.documentElement.lang = lng;
}
